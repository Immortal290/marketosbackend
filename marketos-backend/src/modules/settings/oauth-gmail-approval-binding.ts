import { createHash, timingSafeEqual } from 'crypto';
import { prisma } from '../../lib/prisma';

export interface GmailApprovalPayload {
  userId: string;
  workspaceId: string;
  connectionId: string;
  to: string;
  subject: string;
  textBody: string;
}

export interface GmailApprovalClaim extends GmailApprovalPayload {
  runId: string;
  stepId: string;
}

const GMAIL_APPROVAL_AGENT = 'GmailOAuthSend';
const APPROVAL_MAX_AGE_MS = 15 * 60 * 1000;

function validatePayload(input: GmailApprovalPayload): void {
  for (const field of [
    'userId',
    'workspaceId',
    'connectionId',
    'to',
    'subject',
    'textBody',
  ] as const) {
    if (
      typeof input[field] !== 'string' ||
      !input[field].trim()
    ) {
      throw new Error('Invalid Gmail approval payload');
    }
  }

  if (
    !/^[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}$/i.test(input.to.trim()) ||
    /[\r\n]/.test(input.to) ||
    /[\r\n]/.test(input.subject) ||
    input.subject.length > 500 ||
    Buffer.byteLength(input.textBody, 'utf8') > 1024 * 1024
  ) {
    throw new Error('Invalid Gmail approval payload');
  }
}

export function digestGmailApprovalPayload(
  input: GmailApprovalPayload
): string {
  validatePayload(input);

  // Fixed ordering prevents ambiguity between different payloads.
  const canonical = JSON.stringify([
    1,
    input.userId,
    input.workspaceId,
    input.connectionId,
    input.to,
    input.subject,
    input.textBody,
  ]);

  return createHash('sha256')
    .update(canonical, 'utf8')
    .digest('hex');
}

/**
 * Must be generated by trusted backend code before a user approves.
 * The approval UI must display the complete recipient, subject,
 * and message body. The digest binds those details to this intent.
 */
export function buildGmailApprovalPreview(
  input: GmailApprovalPayload
) {
  return {
    approval_required: true,
    agent: GMAIL_APPROVAL_AGENT,
    to: input.to,
    subject: input.subject,
    textBody: input.textBody,
    gmailApproval: {
      version: 1,
      payloadDigest: digestGmailApprovalPayload(input),
    },
  };
}

/**
 * Claims an already-approved Gmail step exactly once.
 *
 * Only trusted server-side code may call this with an authenticated
 * user ID and the exact payload presented for approval.
 *
 * This function performs no email sending.
 */
export async function claimApprovedGmailPayload(
  input: GmailApprovalClaim
): Promise<void> {
  const expectedDigest = digestGmailApprovalPayload(input);

  if (!input.runId?.trim() || !input.stepId?.trim()) {
    throw new Error('Invalid Gmail approval reference');
  }

  const run = await prisma.workflowRun.findFirst({
    where: {
      id: input.runId,
      userId: input.userId,
      status: 'running',
    },
    include: {
      steps: {
        where: { id: input.stepId },
        take: 1,
      },
    },
  });

  if (!run || run.steps.length !== 1) {
    throw new Error('Gmail workflow approval denied');
  }

  const step = run.steps[0];

  if (
    step.agentName !== GMAIL_APPROVAL_AGENT ||
    !step.requiresApproval ||
    step.status !== 'approved'
  ) {
    throw new Error('Gmail workflow approval denied');
  }

  // Approvals are time-limited. A stale approval cannot be
  // used to perform a new external action.
  const approvedAt = step.updatedAt.getTime();
  const age = Date.now() - approvedAt;

  if (
    !Number.isFinite(age) ||
    age < -60000 ||
    age > APPROVAL_MAX_AGE_MS
  ) {
    throw new Error('Gmail workflow approval expired');
  }

  const output = step.output;

  if (
    !output ||
    typeof output !== 'object' ||
    Array.isArray(output)
  ) {
    throw new Error('Gmail approval binding missing');
  }

  const binding = (output as Record<string, unknown>)
    .gmailApproval;

  if (
    !binding ||
    typeof binding !== 'object' ||
    Array.isArray(binding)
  ) {
    throw new Error('Gmail approval binding missing');
  }

  const version = (binding as Record<string, unknown>).version;
  const storedDigest =
    (binding as Record<string, unknown>).payloadDigest;

  if (
    version !== 1 ||
    typeof storedDigest !== 'string' ||
    !/^[a-f0-9]{64}$/.test(storedDigest)
  ) {
    throw new Error('Gmail approval binding invalid');
  }

  const matches = timingSafeEqual(
    Buffer.from(storedDigest, 'hex'),
    Buffer.from(expectedDigest, 'hex')
  );

  if (!matches) {
    throw new Error('Gmail approval payload changed');
  }

  // Atomic status transition prevents competing requests
  // from claiming the same approved step twice.
  const claimed = await prisma.workflowStep.updateMany({
    where: {
      id: input.stepId,
      runId: input.runId,
      agentName: GMAIL_APPROVAL_AGENT,
      requiresApproval: true,
      status: 'approved',
    },
    data: {
      status: 'running',
    },
  });

  if (claimed.count !== 1) {
    throw new Error('Gmail approval already claimed');
  }
}
